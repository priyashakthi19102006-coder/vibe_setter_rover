/**
 * Fetch current state of the AI Companion engine and local Ollama 3B model
 * Backend route: GET /api/ai/status
 */
export async function getAIStatus() {
  return apiRequest('/ai/status', { method: 'GET' }, DEFAULT_AI_STATUS);
}

/**
 * Send conversational prompt to local Ollama 3B model
 * Backend route: POST /api/ai/query
 * @param {string} prompt - User verbal or text input
 * @param {Array} history - Previous conversation turns
 * @param {boolean} includeTts - Whether to synthesize speech audio
 */
export async function sendVoiceQuery(prompt, history = [], includeTts = true) {
  return apiRequest('/ai/query', {
    method: 'POST',
    body: JSON.stringify({
      prompt,
      history,
      include_tts: includeTts
    })
  }, {
    id: String(Date.now()),
    reply: `Received: "${prompt}". Cyber companion sensors nominal and standing by.`,
    audio_url: null,
    mood: 'energetic',
    model: 'qwen2.5:3b',
    ollama_online: false,
    latency_ms: 45,
    timestamp: new Date().toLocaleTimeString()
  });
}

/**
 * Converts a relative backend audio URL (e.g. /api/ai/tts/audio/123.wav)
 * into a fully-qualified browser playable audio URL.
 */
export function getFullAudioUrl(relativeAudioUrl) {
  if (!relativeAudioUrl) return null;
  if (relativeAudioUrl.startsWith('http://') || relativeAudioUrl.startsWith('https://')) {
    return relativeAudioUrl;
  }
  // Ensure starts with slash
  const cleanPath = relativeAudioUrl.startsWith('/') ? relativeAudioUrl : `/${relativeAudioUrl}`;
  return `${SERVER_HOST}${cleanPath}`;
}

/**
 * Plays speech audio generated by the backend TTS service
 * @param {string} audioUrl - relative or absolute audio URL
 * @returns {Promise<HTMLAudioElement>}
 */
export function playServerAudio(audioUrl) {
  return new Promise((resolve, reject) => {
    const fullUrl = getFullAudioUrl(audioUrl);
    if (!fullUrl) {
      reject(new Error('Invalid audio URL'));
      return;
    }

    const audio = new Audio(fullUrl);
    audio.onended = () => resolve(audio);
    audio.onerror = (e) => reject(e);
    audio.play().catch(reject);
  });
}

/**
 * Synthesize arbitrary text into a speech audio file on the backend
 * Backend route: POST /api/ai/tts/synthesize
 */
export async function synthesizeSpeech(text) {
  return apiRequest('/ai/tts/synthesize', {
    method: 'POST',
    body: JSON.stringify({ text })
  }, null);
}

